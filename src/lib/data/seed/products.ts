/**
 * Every vendor's products except Ananya Sarees (see `products-sarees.ts`),
 * authored directly in the generic shape through `defineProduct()`.
 *
 * A listing declares its option axes (Size, Weight, Colour, ...) and the
 * helper expands them into variants, spreads stock across them and prices
 * them. Category-specific facts go in `attributes`, keyed per the category's
 * attribute definitions in `taxonomy.ts`.
 */

import type {
  AttributeValue,
  FulfillmentType,
  Occasion,
  Product,
  ProductCustomization,
  ProductVariant,
  Tone,
} from "@/lib/types";

import { daysAgo } from "./clock";
import { photos } from "./images";
import { categories, productTypes } from "./taxonomy";

interface OptionSeed {
  name: string;
  values: string[];
  /** Absolute price per value. At most one option per product carries prices. */
  prices?: number[];
  /** Values currently out of stock. */
  soldOut?: string[];
}

interface ProductSeed {
  id: string;
  vendor: string;
  category: string;
  type?: string;
  name: string;
  slug: string;
  subtitle: string;
  short: string;
  description: string;
  story?: string;
  highlights: string[];
  price: number;
  compareAt?: number;
  tone: Tone;
  color?: string;
  tags?: string[];
  occasions?: Occasion[];
  attributes: Record<string, AttributeValue>;
  options?: OptionSeed[];
  stock: number;
  fulfillment?: FulfillmentType[];
  customization?: ProductCustomization;
  featured?: boolean;
  isNew?: boolean;
  /** Days since listing. */
  age: number;
  collections?: string[];
  rating: number;
  reviews: number;
  sales: number;
  tax?: number;
  weight?: number;
  processingDays?: number;
  status?: Product["status"];
  moderationNote?: string;
}

const categoryById = new Map(categories.map((category) => [category.id, category]));
const typeById = new Map(productTypes.map((type) => [type.id, type]));

/** The nearest category (self first) that declares a default product type. */
function inheritedProductType(categoryId: string): string {
  let current = categoryById.get(categoryId);
  while (current) {
    if (current.defaultProductTypeId) return current.defaultProductTypeId;
    current = current.parentId ? categoryById.get(current.parentId) : undefined;
  }
  return "pt-physical";
}

function cartesian(options: OptionSeed[]): Array<Record<string, string>> {
  return options.reduce<Array<Record<string, string>>>(
    (combos, option) =>
      combos.flatMap((combo) => option.values.map((value) => ({ ...combo, [option.name]: value }))),
    [{}],
  );
}

const VENDOR_SKU: Record<string, string> = {
  "vendor-ziva": "ZIV",
  "vendor-saanjh": "SNJ",
  "vendor-stride": "STR",
  "vendor-glow": "GLW",
  "vendor-homemade": "CHF",
  "vendor-crumb": "CRB",
  "vendor-tiffin": "MTH",
  "vendor-freshbasket": "FRB",
  "vendor-petal": "PNT",
  "vendor-techhub": "THB",
  "vendor-crafted": "CRH",
  "vendor-urbanpet": "UPS",
};

function code(value: string): string {
  return value.replace(/[^a-z0-9]/gi, "").slice(0, 4).toUpperCase();
}

function defineProduct(seed: ProductSeed, index: number): Product {
  const productTypeId = seed.type ?? inheritedProductType(seed.category);
  const productType = typeById.get(productTypeId)!;
  const options = seed.options ?? [];
  const combos = options.length ? cartesian(options) : [{}];
  const pricedOption = options.find((option) => option.prices);
  const prefix = `${VENDOR_SKU[seed.vendor] ?? "HT"}-${String(index + 1).padStart(3, "0")}`;

  // Spread stock evenly, remainder to the first variants, nothing to sold-out values.
  const sellable = combos.filter(
    (combo) => !options.some((option) => option.soldOut?.includes(combo[option.name]!)),
  ).length;
  let remainder = seed.stock % Math.max(1, sellable);

  const variants: ProductVariant[] = combos.map((combo, comboIndex) => {
    const soldOut = options.some((option) => option.soldOut?.includes(combo[option.name]!));
    const price = pricedOption
      ? pricedOption.prices![pricedOption.values.indexOf(combo[pricedOption.name]!)]!
      : seed.price;
    let stock = 0;
    if (!soldOut) {
      stock = Math.floor(seed.stock / Math.max(1, sellable)) + (remainder > 0 ? 1 : 0);
      remainder = Math.max(0, remainder - 1);
    }
    const title = options.length ? Object.values(combo).join(" / ") : "Default";

    return {
      id: `${seed.id}-v${comboIndex + 1}`,
      sku: options.length ? `${prefix}-${Object.values(combo).map(code).join("-")}` : prefix,
      title,
      options: combo,
      price,
      compareAtPrice: seed.compareAt ? seed.compareAt + (price - seed.price) : null,
      stockQuantity: productType.tracksInventory ? stock : 999,
      isActive: true,
    };
  });

  const minPrice = Math.min(...variants.map((variant) => variant.price));

  return {
    id: seed.id,
    vendorId: seed.vendor,
    productTypeId,
    categoryId: seed.category,
    collectionIds: seed.collections ?? [],
    name: seed.name,
    slug: seed.slug,
    subtitle: seed.subtitle,
    shortDescription: seed.short,
    description: seed.description,
    story: seed.story ?? "",
    highlights: seed.highlights,
    price: minPrice,
    compareAtPrice: seed.compareAt ?? null,
    color: seed.color ?? "",
    tone: seed.tone,
    tags: seed.tags ?? [],
    occasions: seed.occasions ?? [],
    attributes: seed.attributes,
    options: options.map(({ name, values }) => ({ name, values })),
    variants,
    customization: seed.customization ?? null,
    fulfillmentTypes: seed.fulfillment ?? productType.defaultFulfillment,
    shipping: { weightGrams: seed.weight ?? null, processingDays: seed.processingDays ?? 2 },
    taxRate: seed.tax ?? 12,
    stockQuantity: variants.reduce((total, variant) => total + variant.stockQuantity, 0),
    trackInventory: productType.tracksInventory,
    lowStockThreshold: 3,
    status: seed.status ?? "approved",
    moderationNote: seed.moderationNote ?? null,
    isFeatured: seed.featured ?? false,
    isNew: seed.isNew ?? seed.age < 21,
    isActive: true,
    commissionRate: null,
    rating: seed.rating,
    ratingCount: seed.reviews,
    salesCount: seed.sales,
    images: photos(seed.slug, seed.tone, `${seed.name}, product photograph`),
    metadata: {},
    createdAt: daysAgo(seed.age),
    updatedAt: daysAgo(Math.max(0, seed.age - 1)),
  };
}

