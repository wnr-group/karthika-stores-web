/**
 * Services: first-class marketplace entities, not a kind of product. No
 * stock, no shipping, bought by reserving a slot. See the `Service` type.
 */

import type {
  BookingRules,
  Service,
  ServiceAddon,
  ServiceAvailability,
  ServiceMode,
  ServicePriceUnit,
  Tone,
} from "@/lib/types";

import { daysAgo } from "./clock";
import { photos } from "./images";

interface ServiceSeed {
  id: string;
  vendor: string;
  category: string;
  name: string;
  slug: string;
  subtitle: string;
  short: string;
  description: string;
  highlights: string[];
  includes: string[];
  price: number;
  compareAt?: number;
  unit?: ServicePriceUnit;
  unitLabel?: string;
  duration: number | null;
  modes: ServiceMode[];
  city: string;
  area: string[];
  availability?: Partial<ServiceAvailability>;
  rules?: Partial<BookingRules>;
  addons?: Array<[string, number]>;
  cancellation?: string;
  tags?: string[];
  tone: Tone;
  featured?: boolean;
  age: number;
  collections?: string[];
  rating: number;
  reviews: number;
  bookings: number;
  status?: Service["status"];
}

const WEEKDAYS = [1, 2, 3, 4, 5, 6];
const EVERY_DAY = [0, 1, 2, 3, 4, 5, 6];

const DEFAULT_RULES: BookingRules = {
  advanceNoticeHours: 24,
  maxAdvanceDays: 90,
  requiresConfirmation: false,
  minQuantity: 1,
  maxQuantity: 1,
  quantityLabel: "booking",
  depositPercent: 0,
  maxBookingsPerSlot: 1,
};

const DEFAULT_CANCELLATION =
  "Free cancellation up to 24 hours before the appointment. Within 24 hours, 50% is charged.";

function defineService(seed: ServiceSeed): Service {
  const addons: ServiceAddon[] = (seed.addons ?? []).map(([name, price], index) => ({
    id: `${seed.id}-addon-${index + 1}`,
    name,
    price,
  }));

  return {
    id: seed.id,
    vendorId: seed.vendor,
    categoryId: seed.category,
    collectionIds: seed.collections ?? [],
    name: seed.name,
    slug: seed.slug,
    subtitle: seed.subtitle,
    shortDescription: seed.short,
    description: seed.description,
    highlights: seed.highlights,
    includes: seed.includes,
    price: seed.price,
    compareAtPrice: seed.compareAt ?? null,
    priceUnit: seed.unit ?? "flat",
    unitLabel: seed.unitLabel ?? null,
    durationMinutes: seed.duration,
    modes: seed.modes,
    city: seed.city,
    serviceArea: seed.area,
    availability: {
      days: WEEKDAYS,
      startTime: "09:00",
      endTime: "19:00",
      slotMinutes: 60,
      blackoutDates: [],
      ...seed.availability,
    },
    bookingRules: { ...DEFAULT_RULES, ...seed.rules },
    addons,
    cancellationPolicy: seed.cancellation ?? DEFAULT_CANCELLATION,
    tags: seed.tags ?? [],
    images: photos(seed.slug, seed.tone, `${seed.name}, service photograph`),
    status: seed.status ?? "approved",
    moderationNote: null,
    isActive: true,
    isFeatured: seed.featured ?? false,
    commissionRate: null,
    rating: seed.rating,
    ratingCount: seed.reviews,
    bookingCount: seed.bookings,
    createdAt: daysAgo(seed.age),
    updatedAt: daysAgo(Math.max(0, seed.age - 2)),
  };
}

